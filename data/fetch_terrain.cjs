// Downloads a 21 x 21 elevation grid (~2 km x 2 km, NASA SRTM 30 m via the OpenTopoData API) around every
// preset location and embeds it for the 3D field view.   node data/fetch_terrain.cjs  -> data/terrain.js
const fs = require("fs"), path = require("path");
globalThis.window = globalThis;
require("./presets.js");
const N = 21, SPAN = 2000;
const points = [{ id: "yalova", lat: 40.64, lon: 29.33 }, ...globalThis.PRESET_DATA.map(p => ({ id: p.id, lat: p.lat, lon: p.lon }))];

async function grid(lat, lon) {
  const dLat = SPAN / 111320 / (N - 1), dLon = SPAN / (111320 * Math.cos(lat * Math.PI / 180)) / (N - 1);
  const locs = [];
  // row 0 = north edge, column 0 = west edge
  for (let i = 0; i < N; i++) for (let j = 0; j < N; j++)
    locs.push(`${(lat + ((N - 1) / 2 - i) * dLat).toFixed(5)},${(lon + (j - (N - 1) / 2) * dLon).toFixed(5)}`);
  // OpenTopoData public API: SRTM 30 m, max 100 locations per call, max 1 call per second
  const z = [];
  for (let k = 0; k < locs.length; k += 100) {
    const r = await fetch("https://api.opentopodata.org/v1/srtm30m?locations=" + locs.slice(k, k + 100).join("|"), { signal: AbortSignal.timeout(60000) });
    const j = await r.json();
    if (!r.ok || j.status !== "OK") throw new Error("opentopodata " + r.status + " " + (j.error || ""));
    for (const x of j.results) z.push(x.elevation === null ? NaN : Math.round(x.elevation * 10) / 10);
    await new Promise(res => setTimeout(res, 1200));
  }
  if (z.length !== N * N || z.some(Number.isNaN)) throw new Error("incomplete grid");
  return z;
}

(async () => {
  const file = path.join(__dirname, "terrain.js");
  let out = {};
  if (fs.existsSync(file)) { require(file); out = globalThis.TERRAIN_DATA || {}; } // resume: keep what we have
  const save = () => fs.writeFileSync(file,
    "// Generated by data/fetch_terrain.cjs – NASA SRTM elevation grids (21 x 21 points, ~2 km x 2 km, row 0 = north) via OpenTopoData (srtm30m).\n" +
    "(typeof window !== \"undefined\" ? window : globalThis).TERRAIN_DATA = " + JSON.stringify(out) + ";\n");
  for (const p of points) {
    if (out[p.id]) { console.log(p.id, "kept"); continue; }
    for (let k = 0; ; k++) {
      try { out[p.id] = { n: N, span: SPAN, z: await grid(p.lat, p.lon) }; break; }
      catch (e) { if (k >= 5) { console.log(p.id, "FAILED", e.message); break; } await new Promise(r => setTimeout(r, 15000 * (k + 1))); }
    }
    if (out[p.id]) { const z = out[p.id].z; console.log(p.id, Math.min(...z), "–", Math.max(...z), "m"); save(); }
    await new Promise(r => setTimeout(r, 1500)); // be polite to the free API
  }
  console.log("wrote data/terrain.js with", Object.keys(out).length, "locations");
})();
