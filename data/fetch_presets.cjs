// Downloads and embeds data for the preset locations so the demo works even if an API is slow or offline.
//   node data/fetch_presets.cjs           -> writes data/presets.js
//   node data/fetch_presets.cjs bursa nebraska   -> refreshes only these presets, keeps the others
// Sources (no keys needed):
//   NASA POWER monthly point API (2004-2023), NASA SRTM via Open-Elevation, NASA MODIS MOD13Q1 NDVI via ORNL DAAC,
//   USDA NASS Cropland Data Layer (CropScape GetCDLValue) for US points: crop grown at the point each year.
// Yalova is embedded separately in data/yalova.js.
const fs = require("fs"), path = require("path");
const E = require("../js/engine.js");
const X = require("../js/nasa-extra.js");

const PRESETS = [
  { id: "bursa", name: "Bursa – Karacabey", country: "TR", lat: 40.21, lon: 28.36 },
  { id: "edirne", name: "Edirne", country: "TR", lat: 41.68, lon: 26.56 },
  { id: "konya", name: "Konya", country: "TR", lat: 37.95, lon: 32.7 },
  { id: "adana", name: "Adana", country: "TR", lat: 37.0, lon: 35.32 },
  { id: "harran", name: "Şanlıurfa – Harran", country: "TR", lat: 36.86, lon: 39.03 },
  { id: "iowa", name: "Iowa – Boone County", country: "US", lat: 42.2, lon: -93.8 },
  { id: "kansas", name: "Kansas – McPherson County", country: "US", lat: 38.1, lon: -98.0 },
  { id: "nebraska", name: "Nebraska – York County", country: "US", lat: 40.95, lon: -97.45 }
];
const NDVI_YEAR = 2025;
const CDL_YEARS = [2019, 2020, 2021, 2022, 2023, 2024, 2025];

// CDL category -> our main crop id (null = not a modelled main crop)
const CDL_MAP = {
  "Corn": "corn_grain", "Soybeans": "soybean_main", "Winter Wheat": "wheat", "Dbl Crop WinWht/Soybeans": "wheat",
  "Dbl Crop WinWht/Corn": "wheat", "Dbl Crop WinWht/Sorghum": "wheat", "Sorghum": "sorghum", "Barley": "barley",
  "Sunflower": "sunflower", "Canola": "canola", "Chick Peas": "chickpea_main", "Tomatoes": "tomato",
  "Fallow/Idle Cropland": "fallow"
};

// EPSG:5070 (CONUS Albers Equal Area, NAD83) forward projection, needed by the CDL service.
function albers(lat, lon) {
  const d = Math.PI / 180, a = 6378137, f = 1 / 298.257222101, e2 = 2 * f - f * f, e = Math.sqrt(e2);
  const p1 = 29.5 * d, p2 = 45.5 * d, p0 = 23 * d, l0 = -96 * d;
  const m = ph => Math.cos(ph) / Math.sqrt(1 - e2 * Math.sin(ph) ** 2);
  const q = ph => { const s = Math.sin(ph); return (1 - e2) * (s / (1 - e2 * s * s) - (1 / (2 * e)) * Math.log((1 - e * s) / (1 + e * s))); };
  const m1 = m(p1), m2 = m(p2), q1 = q(p1), q2 = q(p2), q0 = q(p0);
  const n = (m1 * m1 - m2 * m2) / (q2 - q1), C = m1 * m1 + n * q1, r0 = a * Math.sqrt(C - n * q0) / n;
  const r = a * Math.sqrt(C - n * q(lat * d)) / n, th = n * (lon * d - l0);
  return [r * Math.sin(th), r0 - r * Math.cos(th)];
}

async function cdl(lat, lon, year) {
  const [x, y] = albers(lat, lon);
  const url = `https://nassgeodata.gmu.edu/axis2/services/CDLService/GetCDLValue?year=${year}&x=${x.toFixed(1)}&y=${y.toFixed(1)}`;
  const r = await fetch(url, { signal: AbortSignal.timeout(40000) });
  const m = (await r.text()).match(/category: "([^"]+)"/);
  if (!m) throw new Error("no CDL value");
  return { year, category: m[1], crop: CDL_MAP[m[1]] || null };
}

async function retry(fn, n = 3) {
  for (let i = 0; ; i++) {
    try { return await fn(); } catch (e) { if (i >= n - 1) throw e; await new Promise(r => setTimeout(r, 2000 * (i + 1))); }
  }
}

(async () => {
  const only = process.argv.slice(2);
  const file = path.join(__dirname, "presets.js");
  let out = [];
  if (only.length && fs.existsSync(file)) {
    globalThis.window = globalThis; require(file);
    out = (globalThis.PRESET_DATA || []).filter(p => !only.includes(p.id) && PRESETS.some(q => q.id === p.id));
  }
  for (const p of PRESETS) {
    if (only.length && !only.includes(p.id)) continue;
    process.stdout.write(`${p.name} … `);
    const climate = await retry(() => E.fetchPower(p.lat, p.lon, p.name));
    climate.source = "NASA POWER (embedded, fetched " + new Date().toISOString().slice(0, 10) + ")";
    const extra = {};
    try { extra.slope = await retry(() => X.fetchSlope(p.lat, p.lon)); } catch (e) { console.log("slope failed", e.message); }
    try { extra.ndvi = await retry(() => X.fetchNdvi(p.lat, p.lon, NDVI_YEAR)); } catch (e) { console.log("ndvi failed", e.message); }
    if (p.country === "US") {
      const hist = [];
      for (const y of CDL_YEARS) { try { hist.push(await retry(() => cdl(p.lat, p.lon, y))); } catch (e) { /* year not published */ } }
      extra.cdl = hist;
    }
    climate.extra = extra;
    out.push({ ...p, climate });
    console.log("ok", extra.cdl ? extra.cdl.map(h => `${h.year}:${h.category}`).join(", ") : "");
  }
  out.sort((a, b) => PRESETS.findIndex(q => q.id === a.id) - PRESETS.findIndex(q => q.id === b.id));
  const js = "// Generated by data/fetch_presets.cjs – embedded NASA POWER, SRTM, MODIS NDVI and (US) USDA CDL data for preset locations.\n" +
    "(typeof window !== \"undefined\" ? window : globalThis).PRESET_DATA = " + JSON.stringify(out) + ";\n";
  fs.writeFileSync(path.join(__dirname, "presets.js"), js);
  console.log("wrote data/presets.js", (js.length / 1024).toFixed(0) + " KB");
})();
